"""
make_fig4.py
============
Generates Fig 4: Forward vs. reverse asymmetry reveals directional structure.

Panel A: Side-by-side forward and reverse Flow Trees for two example nodes
         — one symmetric hub, one directional funnel.
Panel B: Scatter plot of forward depth vs. reverse depth (and diameter) per node,
         with landmark nodes highlighted.

Run from the mazedyn directory with the mazedyn-test conda environment:
    conda activate mazedyn-test
    python make_fig4.py

Requires: figures/fig3_cache.pkl (generated by make_fig3.py)
"""

