# ── 1. Load data ─────────────────────────────────────────────────────────────
print("Loading data...")
data_path = "data/wikispeedia_paths-and-graph"

article_names = []
with open(f"{data_path}/articles.tsv") as f:
    for line in f:
        line = line.strip()
        if not line or line[0] == "#":
            continue
        article_names.append(line)

edges_df = pd.read_csv(
    f"{data_path}/links.tsv",
    names=["linkSource", "linkTarget"],
    sep="\t",
    skiprows=13,
)
wikiG = nx.DiGraph()
wikiG.add_edges_from(zip(edges_df.linkSource, edges_df.linkTarget))


def get_nth_article(s, n):
    return s.split(";")[n]


def process_path(path):
    assert ";<" * 23 not in path
    for i in range(21, 0, -1):
        seq = "<" + ";<" * i
        if seq in path:
            path = path.replace(seq, f"<{i + 1}")
    nodes = []
    for i, node in enumerate(path.split(";")):
        if "<" in node:
            bk = 1 if node == "<" else int(node[1:])
            node = nodes[i - bk - 1]
        nodes.append(node)
    return nodes


finished_df = pd.read_csv(
    f"{data_path}/paths_finished.tsv",
    names=["hashedIpAddress", "timestamp", "durationInSec", "path", "rating"],
    sep="\t",
    skiprows=16,
)
finished_df["StartAt"] = finished_df["path"].apply(lambda x: get_nth_article(x, 0))
finished_df["EndAt"] = finished_df["path"].apply(lambda x: get_nth_article(x, -1))
finished_df["finished"] = True

unfinished_df = pd.read_csv(
    f"{data_path}/paths_unfinished.tsv",
    names=["hashedIpAddress", "timestamp", "durationInSec", "path", "target", "type"],
    sep="\t",
    skiprows=17,
)
unfinished_df["StartAt"] = unfinished_df["path"].apply(lambda x: get_nth_article(x, 0))
unfinished_df["EndAt"] = unfinished_df["target"]
unfinished_df["finished"] = False

trajs_df = pd.concat([finished_df, unfinished_df]).reset_index(drop=True)
trajs_df = trajs_df.drop_duplicates(subset=["hashedIpAddress", "StartAt", "target"])
trajs_df["traj"] = trajs_df["path"].apply(process_path)
print(f"  Trajectories: {len(trajs_df)}")

# ── 2. Node properties ───────────────────────────────────────────────────────
node_counts, node_outdegrees, node_zipf = {}, {}, {}
STOP_WORDS = {"a", "an", "the", "and", "for", "of"}
for traj in trajs_df.traj:
    for n in traj:
        node_counts[n] = node_counts.get(n, 0) + 1
for n in node_counts:
    if n in wikiG:
        node_outdegrees[n] = wikiG.out_degree(n)
        words = [w for w in n.split("_") if w.lower() not in STOP_WORDS]
        node_zipf[n] = np.mean([zipf_frequency(w, "en") for w in words]) if words else 0


def top_k(d, k, restrict=None):
    keys = list(restrict or d.keys())
    return set(sorted(keys, key=lambda x: d.get(x, 0), reverse=True)[:k])


most_common_nodes = top_k(node_counts, 500)
most_common_nodes.discard("Wikipedia_Text_of_the_GNU_Free_Documentation_License")
outdegree_landmarks = top_k(node_outdegrees, 50, restrict=most_common_nodes)
player_landmarks = top_k(node_counts, 50, restrict=most_common_nodes)
all_landmarks = outdegree_landmarks | player_landmarks

MIN_PATH = 6
TRAJ_PER_TREE = 13
K_FOLD = 5
rev_wikiG = wikiG.reverse()


# ── 3. Flow tree helpers ─────────────────────────────────────────────────────
def make_traj_dict(nodes):
    d = {n: [] for n in nodes}
    for traj in trajs_df.traj:
        for i in range(len(traj) - MIN_PATH - 1):
            if traj[i] in nodes:
                d[traj[i]].append(traj[i : i + MIN_PATH])
    return d


def make_rev_traj_dict(nodes):
    d = {n: [] for n in nodes}
    for traj in trajs_df.traj:
        for i in range(MIN_PATH, len(traj)):
            if traj[i] in nodes:
                d[traj[i]].append(list(reversed(traj[i - MIN_PATH : i])))
    return d


def sample_trees(traj_dict, graph, k_fold=K_FOLD, n=TRAJ_PER_TREE):
    result = {}
    for node, trajs in traj_dict.items():
        human_trees = []
        for _ in range(k_fold):
            sampled = (
                trajs
                if len(trajs) <= n
                else [trajs[i] for i in np.random.choice(len(trajs), n, replace=False)]
            )
            if not sampled:
                continue
            G = generate_flow_tree_from_trajs(sampled, END_NODE="1")
            G = nx.relabel.convert_node_labels_to_integers(G, ordering="default")
            human_trees.append(G)
        result[node] = {"human": human_trees}
    return result


def tree_depth(G, root=0):
    if G.number_of_nodes() < 2:
        return 0
    depths = nx.single_source_shortest_path_length(G, root)
    return max(depths.values())


def tree_diameter(G):
    if G.number_of_nodes() < 2:
        return 0
    try:
        return nx.diameter(G)
    except Exception:
        return 0


# ── 4. Compute or load ───────────────────────────────────────────────────────
if os.path.exists(CACHE_FILE):
    print(f"Loading cached flow trees from {CACHE_FILE}...")
    with open(CACHE_FILE, "rb") as f:
        cache = pickle.load(f)
    ft_dict = cache["ft_dict"]
    rev_ft_dict = cache["rev_ft_dict"]
else:
    print("Computing flow trees (run make_fig3.py first to cache)...")
    td = make_traj_dict(most_common_nodes)
    rev_td = make_rev_traj_dict(most_common_nodes)
    ft_dict = sample_trees(td, wikiG)
    rev_ft_dict = sample_trees(rev_td, rev_wikiG)
    with open(CACHE_FILE, "wb") as f:
        pickle.dump({"ft_dict": ft_dict, "rev_ft_dict": rev_ft_dict}, f)

# ── 5. Build per-node forward/reverse metric arrays ─────────────────────────
print("Computing per-node forward/reverse metrics...")
records = []
for node in most_common_nodes:
    fwd_trees = ft_dict.get(node, {}).get("human", [])
    rev_trees = rev_ft_dict.get(node, {}).get("human", [])
    if not fwd_trees or not rev_trees:
        continue
    fwd_depths = [tree_depth(G) for G in fwd_trees]
    rev_depths = [tree_depth(G) for G in rev_trees]
    fwd_diameters = [tree_diameter(G) for G in fwd_trees]
    rev_diameters = [tree_diameter(G) for G in rev_trees]
    fwd_bfs = [
        np.mean([FT.degree(node) for node in FT.nodes() if FT.degree(node) != 1])
        for FT in fwd_trees
    ]
    rev_bfs = [
        np.mean([FT.degree(node) for node in FT.nodes() if FT.degree(node) != 1])
        for FT in rev_trees
    ]
    records.append(
        {
            "node": node,
            "fwd_depth": np.mean(fwd_depths),
            "rev_depth": np.mean(rev_depths),
            "fwd_diameter": np.mean(fwd_diameters),
            "rev_diameter": np.mean(rev_diameters),
            "fwd_bf": np.mean(fwd_bfs),
            "rev_bf": np.mean(rev_bfs),
            "is_landmark": node in all_landmarks,
            "is_outd_lm": node in outdegree_landmarks,
            "is_player_lm": node in player_landmarks,
        }
    )
df = pd.DataFrame(records)
print(f"  {len(df)} nodes with both forward and reverse trees")

# ── 6. Fig 4A: Three example node types ─────────────────────────────────────
print("Making Fig 4A...")

df["asym_depth_score"] = np.abs(df["fwd_depth"] - df["rev_depth"])
df["asym_bf_score"] = np.abs(df["fwd_bf"] - df["rev_bf"])
